// Prompt editors save independently, keep edits during rapid input, and reset only the selected instruction.
import { setup, imp, tick } from './harness.mjs';
import assert from 'assert';
const { store, w } = setup({});
const { DEFAULT_HIGHLIGHT_PROMPT, DEFAULT_SUMMARY_PROMPT } = await imp('modules/pagePrompts.js');
const { initPromptSettings, savePromptSettings } = await imp('modules/promptSettings.js');
const root = document.getElementById('promptSettingsRoot');
await initPromptSettings(root);
const highlight = root.querySelector('#highlightPrompt');
const summary = root.querySelector('#prompt');
assert.equal(highlight.value, DEFAULT_HIGHLIGHT_PROMPT);
assert.equal(summary.value, DEFAULT_SUMMARY_PROMPT);
assert(!root.querySelector('select, [data-act="phil"], [data-act="tab"]'), 'only the two prompt editors remain');
assert.equal(root.querySelectorAll('textarea').length, 2);
assert(highlight.compareDocumentPosition(summary) & w.Node.DOCUMENT_POSITION_FOLLOWING, 'highlight editor comes first');
const input = (element, text) => { element.value = text; element.dispatchEvent(new w.Event('input', { bubbles: true })); };
input(highlight, 'Choose exact recommendations.');
input(summary, 'Explain hidden tradeoffs.');
await tick(600);
assert.equal(store.highlightPrompt, 'Choose exact recommendations.');
assert.equal(store.prompt, 'Explain hidden tradeoffs.');
assert.equal(document.activeElement, document.body, 'saving does not steal focus or rerender editors');
root.querySelector('[data-reset="highlightPrompt"]').click(); await tick();
assert.equal(highlight.value, DEFAULT_HIGHLIGHT_PROMPT);
assert.equal(store.highlightPrompt, '');
assert.equal(store.highlightPromptMode, 'default');
assert.equal(store.prompt, 'Explain hidden tradeoffs.', 'highlight reset leaves summary intact');
input(highlight, 'Custom highlights <script>bad()</script>');
await savePromptSettings();
assert.equal(store.highlightPrompt, highlight.value, 'Save flushes an edit before the debounce fires');
root.querySelector('[data-reset="prompt"]').click(); await tick();
assert.equal(store.prompt, '');
assert.equal(store.mainOutputPromptMode, 'default');
assert.equal(store.highlightPrompt, 'Custom highlights <script>bad()</script>', 'summary reset leaves highlights intact');
const other = document.createElement('div');
await initPromptSettings(other);
assert.equal(other.querySelector('#highlightPrompt').value, store.highlightPrompt, 'custom instructions survive reload');
assert(!other.querySelector('script'), 'stored text is shown safely');
console.log('TEST 33 OK');
w.close();
