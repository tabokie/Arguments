// Native highlights survive storage restoration on query-identified discussion pages and stay separate across threads.
import assert from 'assert';
import { setup, imp, tick } from './harness.mjs';
const { dom, w, store } = setup({});
chrome.runtime.id = 'abc';
dom.reconfigure({ url: 'https://news.ycombinator.com/item?id=50047422&utm_source=test#comments' });
globalThis.CSS = { highlights: new Map() };
globalThis.Highlight = class extends Set {};
const sentences = Array.from({ length: 203 }, (_, index) => `Claim ${index + 1} expresses an independent argument that must stay visible.`);
document.body.innerHTML = '<table id="hnmain"><tbody><tr><td><table class="comment-tree"><tbody>' + sentences.map((sentence, index) => `<tr class="comtr" id="${index}"><td><div class="commtext">${sentence}</div></td></tr>`).join('') + '</tbody></table></td></tr></tbody></table>';
const H = await imp('content/highlighter.js');
const { SK } = await imp('modules/storageKeys.js');
assert(H.applyGhostHighlights(sentences).every(match => match.status === 'matched'));
assert.equal(CSS.highlights.get('aish-ghost').size, 203, 'all selected sentences are painted');
H.restoreAnnotations();
await tick(100);
assert.equal(CSS.highlights.get('aish-ghost').size, 203, 'restoration must not erase matched highlights');
assert(store[SK.annotations].every(annotation => annotation.url === 'https://news.ycombinator.com/item?id=50047422'), 'normalization preserves the content identifier while dropping tracking and fragments');
H.clearHighlightElements();
H.restoreAnnotations();
await tick(100);
assert.equal(CSS.highlights.get('aish-ghost').size, 203, 'all saved highlights return after page marks are cleared');
dom.reconfigure({ url: 'https://news.ycombinator.com/item?id=50047423' });
H.restoreAnnotations();
await tick(100);
assert.equal(CSS.highlights.get('aish-ghost').size, 0, 'another discussion does not inherit highlights from the first discussion');
H.applyGhostHighlights([sentences[0]]);
assert.equal(store[SK.annotations].length, 204, 'identical text on a second thread remains a distinct annotation');
dom.reconfigure({ url: 'https://news.ycombinator.com/item?id=50047422' });
H.restoreAnnotations();
await tick(100);
assert.equal(CSS.highlights.get('aish-ghost').size, 203);
delete globalThis.CSS;
delete globalThis.Highlight;
console.log('TEST 135 OK');
w.close();
