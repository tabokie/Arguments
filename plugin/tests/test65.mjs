// Markdown exports retain highlights from an empty main output, without retired metadata or tag-derived links.
import assert from 'assert';
import { setup, imp } from './harness.mjs';
const { w, store } = setup({});
const { articleToMarkdown, buildArchiveFiles } = await imp('modules/markdownArchive.js');
const { SK } = await imp('modules/storageKeys.js');
const source = 'A source argument remains useful without exceptional insights.';
const article = { id: 'one', title: 'Arguments', url: 'https://example.test/one', timestamp: '2026-10-01', summary: '', tags: ['quasar'], moodScore: 1, paper: 'yes', doi: '10.1234/test', meta: { paper: { journal: 'Legacy journal' } } };
const text = articleToMarkdown(article, { highlights: [{ text: source, type: 'ghost' }] });
assert(text.includes(source), 'highlight-only analyses export complete source sentences');
assert(!/^(?:tags|mood|doi|journal):/m.test(text), 'retired metadata does not reappear in Markdown');
store[SK.articlesIndex] = [article, { ...article, id: 'two', title: 'Other', url: 'https://example.test/two' }];
store['articles:rec:one'] = { summary: '', highlights: [{ text: source, status: 'unavailable' }] };
store['articles:rec:two'] = { summary: '<p>An unrelated response.</p>' };
const files = await buildArchiveFiles();
assert.equal(files.length, 2);
assert(files[0].text.includes(source), 'archive export includes saved highlights without page annotations');
const { fetchAnnotationsForArticle } = await imp('modules/annotationExporter.js');
assert.equal((await fetchAnnotationsForArticle(article))[0].text, source, 'single-article exports load saved selections from the full record');
store[SK.annotations] = [{ url: article.url, text: source, type: 'ghost', dismissed: true }];
assert.deepEqual(await fetchAnnotationsForArticle(article), [], 'dismissed selections are not restored during export');
assert(files.every(file => !file.text.includes('[[Other]]') && !file.text.includes('[[Arguments]]')), 'shared legacy tags cannot create related links');
assert(files.every(file => file.name.startsWith('Arguments/')), 'exports use the fork name');
assert.equal(store[SK.articlesIndex][0].tags[0], 'quasar', 'stored legacy metadata remains untouched');
console.log('TEST 65 OK');
w.close();
